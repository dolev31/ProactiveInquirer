"""Canary nonces: the only firewall layer that catches leakage through a STRING.

The other three layers are structural and stop leakage through CODE — an import contract, a
type wall whose field names cannot collide, and a process split that leaves PI_GOLD_ROOT
unset in every rollout worker. None of them can stop a human pasting a gold answer into a
prompt template, or an adapter helpfully interpolating a field it should not have had.

So every gold graph carries a nonce that appears NOWHERE else. The nonce is emitted into the
gold artifact, registered in data/canaries/, and scanned against every serialized request in
the cache. A hit means gold text reached a model, and the run is void — there is no benign
explanation, which is exactly what makes the check worth having.

RELEASE NOTE: nonces are stripped from released gold and regenerated by `reseed()`, so a
published canary list cannot be used to reverse-engineer what was withheld.
"""

from __future__ import annotations

import hashlib
import os
import secrets
from dataclasses import dataclass
from pathlib import Path

PREFIX = "PINQCANARY"


def mint(suite: str, task_key: str, salt: str | None = None) -> str:
    """Deterministic under a salt (so a build is reproducible), unguessable without it."""
    salt = salt or os.environ.get("PI_CANARY_SALT") or secrets.token_hex(8)
    digest = hashlib.sha256(f"{salt}|{suite}|{task_key}".encode()).hexdigest()[:16].upper()
    return f"{PREFIX}_{digest}"


@dataclass(frozen=True, slots=True)
class CanaryHit:
    canary: str
    where: str
    excerpt: str


def registry_path(root: Path | None = None) -> Path:
    return (root or Path.cwd()) / "data" / "canaries" / "canaries.txt"


def register(canaries: set[str], root: Path | None = None) -> Path:
    """Append-only. A canary that has ever been minted stays scanned forever, so a stale
    build's leak is still caught after the graph that produced it was regenerated."""
    p = registry_path(root)
    p.parent.mkdir(parents=True, exist_ok=True)
    existing = set(p.read_text().split()) if p.exists() else set()
    p.write_text("\n".join(sorted(existing | canaries)) + "\n")
    return p


def load(root: Path | None = None) -> set[str]:
    p = registry_path(root)
    return set(p.read_text().split()) if p.exists() else set()


def scan_text(text: str, canaries: set[str], where: str = "") -> list[CanaryHit]:
    hits = []
    for c in canaries:
        i = text.find(c)
        if i >= 0:
            hits.append(CanaryHit(c, where, text[max(0, i - 40) : i + len(c) + 40]))
    return hits


def scan_tree(root: Path, canaries: set[str], *, suffixes: tuple[str, ...] = (".json", ".jsonl")):
    """Scan a directory of cached requests / trajectories.

    Deliberately scans the CACHE, not the prompts: a prompt template can look innocent while
    the value interpolated into it at runtime is not, and the cache holds what was actually
    sent.
    """
    hits: list[CanaryHit] = []
    if not canaries or not root.exists():
        return hits
    for p in root.rglob("*"):
        if p.is_file() and p.suffix in suffixes:
            try:
                hits.extend(scan_text(p.read_text(errors="ignore"), canaries, str(p)))
            except OSError:
                continue
    return hits


def strip(text: str) -> str:
    """Remove every canary token from a string, for release artifacts."""
    import re

    return re.sub(rf"{PREFIX}_[0-9A-F]{{16}}", "", text)
